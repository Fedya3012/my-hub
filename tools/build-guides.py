#!/usr/bin/env python3
# Builds the in-app "Hướng dẫn sử dụng" pages (web/js/modules/guides/content.js) from docs/guides/*.md
# and copies the screenshots to web/js/modules/guides/img/. Needs `pip install markdown`.
# Usage: python3 tools/build-guides.py   (then node tools/sync-versions.js)
# A new app guide = add docs/guides/3x-<name>.md and an entry in PAGES below.
import json, pathlib, re, shutil, unicodedata
import markdown

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / 'docs/guides', ROOT / 'web/js/modules/guides'
PAGES = [  # (group, file, page id, label)
  ('Bắt đầu', '10-android', 'android', 'Android (Obtainium)'),
  ('Bắt đầu', '11-windows', 'windows', 'Windows'),
  (None, '20-dong-bo', 'dong-bo', 'Đồng bộ'),
  ('Ứng dụng', '30-thu-vien', 'thu-vien', 'Thư viện'),
  ('Ứng dụng', '31-quan-ly-ung-dung', 'quan-ly-ung-dung', 'Quản lý ứng dụng'),
  ('Ứng dụng', '32-trinh-phat-nhac', 'trinh-phat-nhac', 'Trình phát nhạc'),
  ('Ứng dụng', '33-sach', 'sach', 'Sách'),
  ('Ứng dụng', '34-xuong-viet', 'xuong-viet', 'Xưởng Viết'),
  ('Ứng dụng', '35-cai-dat', 'cai-dat', 'Cài đặt'),
  (None, '40-phat-hanh', 'phat-hanh', 'Phát hành'),
]
fid = {f + '.md': pid for _, f, pid, _ in PAGES}
slug = lambda s: re.sub(r'[^a-z0-9]+', '-', unicodedata.normalize('NFKD', s.lower().replace('đ', 'd')).encode('ascii', 'ignore').decode()).strip('-')
strip = lambda s: re.sub('<[^>]+>', '', s)

(OUT / 'img').mkdir(exist_ok=True)
for p in (SRC / 'img').glob('*.webp'): shutil.copy(p, OUT / 'img' / p.name)

out, n, last = [], 0, object()
for group, f, pid, label in PAGES:
    if group != last or group is None: n += 1; k = 0
    last = group; k += 1
    num = f'{n}.{k}' if group else f'{n}'
    md = (SRC / (f + '.md')).read_text()
    md = re.sub(r'!\[([^\]]*)\]\(img/([^)]+)\)', r'\n\n<figure><img data-src="\2" alt="\1"><figcaption>\1</figcaption></figure>\n\n', md)
    md = re.sub(r'\]\((\d\d-[\w-]+\.md)\)', lambda m: f'](#guides/{fid[m.group(1)]})', md)
    h = markdown.markdown(md, extensions=['tables'])
    heads, c2, c3 = [], 0, 0
    def hd(m):
        global c2, c3
        lvl, text = m.group(1), m.group(2)
        if lvl == '1': return ''
        sid = slug(strip(text))
        if lvl == '2': c2 += 1; c3 = 0; no = f'{num}.{c2}'
        else: c3 += 1; no = f'{num}.{c2}.{c3}'
        heads.append({'id': sid, 'num': no, 'title': strip(text), 'level': int(lvl)})
        return f'<h{lvl} data-sec="{sid}">{text}</h{lvl}>'
    h = re.sub(r'<h([123])>(.*?)</h\1>', hd, h)
    h = re.sub(r'<p>\s*(<figure>.*?</figure>)\s*</p>', r'\1', h, flags=re.S)
    h = h.replace('<table>', '<div class="gd-tw"><table>').replace('</table>', '</table></div>')
    h = re.sub(r'(?<![">/])(https://[\w./?=&%-]+[\w/])', r'<a href="\1" target="_blank" rel="noopener">\1</a>', h)
    h = re.sub(r'<a href="(https?:[^"]+)">', r'<a href="\1" target="_blank" rel="noopener">', h)
    title = re.search(r'^# (.+)$', md, re.M).group(1)
    out.append({'id': pid, 'num': num, 'group': group, 'label': label, 'title': title, 'sections': heads, 'html': h})

(OUT / 'content.js').write_text('// Generated by tools/build-guides.py from docs/guides/*.md. Do not edit by hand.\nexport const PAGES = '
                                + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print(f'{len(out)} pages -> {OUT / "content.js"}')
