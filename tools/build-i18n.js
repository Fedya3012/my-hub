// Builds web/js/core/i18n-en.js from tools/i18n/en.json (Vietnamese phrase -> English).
// Also reports phrases that exist in the code but are missing from en.json.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const root = path.join(__dirname, '..');
const load = (f) => { try { return JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n', f), 'utf8')); } catch { return {}; } };
// en.json: phrases found in the code. extra.json: hand-written ones (index.html, strings built from parts).
const dict = { ...load('en.json'), ...load('extra.json') };
const tmp = path.join(require('os').tmpdir(), 'phrases.json');
cp.execFileSync('node', [path.join(__dirname, 'extract-i18n.js'), tmp]);
const missing = JSON.parse(fs.readFileSync(tmp, 'utf8')).filter(p => !(p in dict));
const out = '// GENERATED by tools/build-i18n.js from tools/i18n/en.json. Edit that file, not this one.\nexport default ' + JSON.stringify(dict, null, 0).replace(/","/g, '",\n"') + ';\n';
fs.writeFileSync(path.join(root, 'web', 'js', 'core', 'i18n-en.js'), out);
console.log(Object.keys(dict).length, 'phrases written;', missing.length, 'phrases in code not yet translated');
if (missing.length && process.argv.includes('--list')) console.log(missing.join('\n'));
